test('--write on a pre-Scope backlog: both transforms in one run; the result passes backlog-check and keeps ids, Status, Jira, Ref and every AC line', () => {
  const dir = project();
  const before = read(dir);
  const r = run(dir, '--could', 'R2', '--write');
  assert.equal(r.code, 0, r.out);
  assert.match(r.out, /^backlog-migrate: wrote \.agents\/backlog\.md and 3 Epic file\(s\) in \.agents\/backlog\/$/m);
  assert.match(r.out, /^story map: regenerated$/m);
  const after = read(dir);

  const check = spawnSync(process.execPath, [CHECKER, '--root', dir], { encoding: 'utf8' });
  assert.equal(check.status, 0, check.stdout + check.stderr);

  const old = parseTables(before).find((t) => t.header.includes('Wave')).rows;
  const now = taskRows(after);
  assert.deepEqual(now.map((t) => t.id), old.map((row) => row.ID));
  for (const row of old) {
    const t = now.find((x) => x.id === row.ID);
    assert.equal(t.status, row.Status);
    assert.equal(t.jira ?? '—', row.Jira);
    assert.equal(t.ref ?? '—', row.Ref);
  }
  const acLines = (md) => md.split('\n').filter((l) => /\*\*E\d+-\d+\.AC\d+\*\*/.test(l));
  assert.deepEqual(fs.readdirSync(epicDir(dir)).sort(), EPIC_NAMES);
  assert.deepEqual(EPIC_NAMES.flatMap((n) => acLines(readEpic(dir, n))), acLines(before));
  assert.deepEqual(acLines(after), []);
  assert.doesNotMatch(after, /^## Acceptance criteria/m);
  assert.match(after, /^\*\*Date:\*\* 2026-10-10 · \*\*Source PRD:\*\* `docs\/PRD\.md` · \*\*Sizes:\*\* M=4 · H=8 · XH=16 points · \*\*Detail:\*\* full$/m);

  assert.doesNotMatch(after, /\| Wave \||\| Slice \||## Parallel plan|lanes:begin/);
  const outsideAt = after.indexOf('## Outside the dev backlog\n| ID | Owner | Item | Needed by | Starts after | Traces | Notes |\n|----|-------|------|-----------|--------------|--------|-------|\n\n## External blockers');
  assert.ok(outsideAt > 0, 'outside section sits right before ## External blockers');
  assert.match(after, /<!-- storymap:begin -->\n### FL-1 — Place order \(critical\)/);
});

