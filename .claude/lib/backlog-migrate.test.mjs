test('every non-table line stays byte-identical; the header prose about Wave / Slice is untouched', () => {
  const src = backlogMd();
  const { md } = migrate(src, { could: ['R2'] });
  const tableLines = (text) => {
    const t = parseTables(text).find((x) => x.header.includes('Size'));
    return new Set([t.line, t.line + 1, ...t.rows.map((r) => r._line)]);
  };
  const strip = (text, drop) => text.split('\n').filter((_, i) => !drop(i + 1, text));
  const srcLines = src.split('\n');
  const pStart = srcLines.findIndex((l) => l.startsWith('## Parallel plan'));
  const pStop = srcLines.findIndex((l, i) => i > pStart && /^## /.test(l));
  const srcTable = tableLines(src);
  const kept = strip(src, (n) => srcTable.has(n) || (n - 1 >= pStart && n - 1 < pStop));
  const outLines = md.split('\n');
  const oStart = outLines.findIndex((l) => l.startsWith('## Outside the dev backlog'));
  const outTable = tableLines(md);
  const result = strip(md, (n) => outTable.has(n) || (n - 1 >= oStart && n - 1 < oStart + 4));
  assert.deepEqual(result, kept);
  assert.ok(md.includes('Wave 0 is the walking skeleton; Slice WS / R1 / R2 are the release slices.'));
});

