test('dry run prints the summary and writes nothing', () => {
  const dir = project();
  const r = refused(dir, 0, '--could', 'R2');
  assert.match(r.out, /dry run — nothing written/);
  assert.match(r.out, /^Tasks per scope: CORE 2 · MUST 4 · COULD 1$/m);
  assert.match(r.out, /^CORE: E0-1, E0-2$/m);
  assert.match(r.out, /^removed: Wave and Slice columns, ## Parallel plan$/m);
  assert.match(r.out, /^added: Scope column, ## Outside the dev backlog$/m);
  for (const n of NOTES) assert.ok(r.out.includes(`note: ${n}`), n);
  assert.deepEqual(fs.readdirSync(path.join(dir, '.agents')), ['backlog.md']);
});

test('--write: result passes backlog-check and keeps ids, Status, Jira, Ref and every AC line', () => {
  const dir = project();
  const before = read(dir);
  const r = run(dir, '--could', 'R2', '--write');
  assert.equal(r.code, 0, r.out);
  assert.match(r.out, /^backlog-migrate: wrote \.agents\/backlog\.md$/m);
  assert.match(r.out, /^story map: regenerated$/m);
  const after = read(dir);

  const check = spawnSync(process.execPath, [CHECKER, '--root', dir], { encoding: 'utf8' });
  assert.equal(check.status, 0, check.stdout + check.stderr);

  const old = parseTables(before).find((t) => t.header.includes('Wave')).rows;
  const now = taskRows(after);
  assert.deepEqual(now.map((t) => t.id), old.map((row) => row.ID));
  for (const row of old) {
    const t = now.find((x) => x.id === row.ID);
    assert.equal(t.status, row.Status);
    assert.equal(t.jira ?? '—', row.Jira);
    assert.equal(t.ref ?? '—', row.Ref);
  }
  const acLines = (md) => md.split('\n').filter((l) => /\*\*E\d+-\d+\.AC\d+\*\*/.test(l));
  assert.deepEqual(acLines(after), acLines(before));

  assert.doesNotMatch(after, /\| Wave \||\| Slice \||## Parallel plan|lanes:begin/);
  const outsideAt = after.indexOf('## Outside the dev backlog\n| ID | Owner | Item | Needed by | Traces | Notes |\n|----|-------|------|-----------|--------|-------|\n\n## External blockers');
  assert.ok(outsideAt > 0, 'outside section sits right before ## External blockers');
  assert.match(after, /<!-- storymap:begin -->\n### FL-1 — Place order \(critical\)/);
});

test('scope mapping: Wave 0 → CORE, --could R2 → COULD, the rest MUST', () => {
  const { md } = migrate(backlogMd(), { could: ['R2'] });
  assert.equal(scopeOf(md, 'E0-1'), 'CORE');
  assert.equal(scopeOf(md, 'E0-2'), 'CORE');
  for (const id of ['E1-1', 'E1-2', 'E1-3', 'E2-1']) assert.equal(scopeOf(md, id), 'MUST', id);
  assert.equal(scopeOf(md, 'E2-2'), 'COULD');
  const none = migrate(backlogMd()).md;
  assert.equal(scopeOf(none, 'E2-2'), 'MUST');
});

