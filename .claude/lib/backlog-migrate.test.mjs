function project(backlog = backlogMd()) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'backlog-migrate-'));
  fs.mkdirSync(path.join(dir, '.agents'));
  fs.mkdirSync(path.join(dir, 'docs'));
  fs.writeFileSync(path.join(dir, 'docs', 'PRD.md'), PRD);
  fs.writeFileSync(path.join(dir, 'docs', 'discovery.md'), DISCOVERY);
  fs.writeFileSync(path.join(dir, 'docs', 'architecture.md'), ARCHITECTURE);
  if (backlog !== null) fs.writeFileSync(path.join(dir, '.agents', 'backlog.md'), backlog);
  return dir;
}

function run(dir, ...flags) {
  const r = spawnSync(process.execPath, [SCRIPT, '--root', dir, ...flags], { encoding: 'utf8' });
  return { code: r.status, out: r.stdout + r.stderr };
}

const read = (dir) => fs.readFileSync(path.join(dir, '.agents', 'backlog.md'), 'utf8');
const taskRows = (md) => parseBacklog(md).tasks;
const scopeOf = (md, id) => taskRows(md).find((t) => t.id === id).scope;
const epicDir = (dir) => path.join(dir, '.agents', 'backlog');
const readEpic = (dir, name) => fs.readFileSync(path.join(epicDir(dir), name), 'utf8');
const EPIC_NAMES = ['E0-foundation.md', 'E1-ordering.md', 'E2-reporting.md'];

/** Every file under `.agents/` with its bytes and mtime — "nothing written" means this is unchanged. */
function snapshot(dir) {
  const out = {};
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out[path.relative(dir, p)] = { text: fs.readFileSync(p, 'utf8'), mtime: fs.statSync(p).mtimeMs };
    }
  };
  walk(path.join(dir, '.agents'));
  return out;
}

/** Run, then assert the exit code and that every file under `.agents/` is byte-identical. */
function refused(dir, code, ...flags) {
  const before = snapshot(dir);
  const r = run(dir, ...flags);
  assert.equal(r.code, code, r.out);
  assert.deepEqual(snapshot(dir), before, 'every file under .agents/ must stay byte-identical');
  return r;
}

/** Criterion and continuation lines per `## <Task id>` heading of an Epic file. */
function criteriaByTask(text) {
  const out = {};
  let id = null;
  let inCriteria = false;
  for (const line of text.split(/\r?\n/)) {
    const h = /^## (E\d+-\d+) /.exec(line);
    if (h) { id = h[1]; inCriteria = false; out[id] = []; continue; }
    if (/^### Acceptance criteria$/.test(line)) { inCriteria = true; continue; }
    if (id && inCriteria && line.trim() !== '') out[id].push(line);
  }
  return out;
}

/** The ACS blocks as `{ <Task id>: [block lines without the heading and trailing blanks] }`. */
function blocksOf(acs) {
  const out = {};
  for (const block of acs.split(/\n(?=### )/)) {
    const [head, ...rest] = block.split('\n');
    while (rest.length && rest[rest.length - 1].trim() === '') rest.pop();
    out[/^### (E\d+-\d+)/.exec(head)[1]] = rest;
  }
  return out;
}

/** A backlog already on Scope that still carries its `## Acceptance criteria` section. */
function scopedMd(acs = ACS) {
  const scoped = migrate(backlogMd({ acs: null, parallel: false }), { could: ['R2'] }).md;
  return scoped.replace('## Story map', `## Acceptance criteria\n${acs}\n\n## Story map`);
}

