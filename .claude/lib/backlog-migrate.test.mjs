test('a table without Relates / Chain migrates, and one with them keeps them by name', () => {
  const plain = migrate(backlogMd()).md;
  assert.ok(plain.includes('| ID | Epic | Task | Type | Size | Pts | Depends on | Scope | Node | Traces | Status | Jira | Ref |'));
  assert.ok(plain.includes('| ---- | ------ | ------ | ------ | ------ | ----- | ------------ | ------- | ------ | -------- | -------- | ------ | ----- |'));

  const header = '| ID | Epic | Task | Type | Size | Pts | Depends on | Relates | Wave | Chain | Slice | Node | Traces | Status | Jira | Ref |';
  const separator = '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|';
  const rows = ROWS.map((r) => {
    const c = r.split(/(?<!\\)\|/).slice(1, -1).map((x) => x.trim());
    const relates = c[0] === 'E2-2' ? 'E2-1' : '—';
    return `| ${[...c.slice(0, 7), relates, c[7], '—', ...c.slice(8)].join(' | ')} |`;
  });
  const dir = project(backlogMd({ header, separator, rows }));
  assert.equal(run(dir, '--could', 'R2', '--write').code, 0);
  const after = read(dir);
  const t = taskRows(after).find((x) => x.id === 'E2-2');
  assert.deepEqual(t.relates, ['E2-1']);
  assert.equal(t.scope, 'COULD');
  assert.ok(after.includes('| ID | Epic | Task | Type | Size | Pts | Depends on | Relates | Scope | Chain | Node | Traces | Status | Jira | Ref |'));
  assert.equal(spawnSync(process.execPath, [CHECKER, '--root', dir]).status, 0);
});

