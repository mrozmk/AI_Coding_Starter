test('missing or empty backlog and bad flags → exit 2', () => {
  assert.equal(run(project(null)).code, 2);
  assert.equal(run(project('  \n')).code, 2);
  const dir = project();
  assert.equal(refused(dir, 2, '--could').code, 2);
  assert.equal(refused(dir, 2, '--bogus').code, 2);
  assert.match(run(dir, '--help').out, /^usage: backlog-migrate\.mjs/m);
});

test('migrate is pure and throws MigrateStop with the exit code', () => {
  const src = backlogMd();
  assert.throws(() => migrate(src, { could: ['nope'] }), (e) => e instanceof MigrateStop && e.code === 2);
  assert.throws(() => migrate(src, { could: ['WS'] }), (e) => e instanceof MigrateStop && e.code === 1);
  const once = migrate(src);
  assert.equal(migrate(once.md).summary.alreadyMigrated, true);
  assert.equal(migrate(once.md).md, once.md);
});

test('CRLF line endings are kept on rewritten and added lines', () => {
  const { md } = migrate(backlogMd().replace(/\n/g, '\r\n'));
  assert.ok(!/[^\r]\n/.test(md), 'every newline stays CRLF');
  assert.equal(scopeOf(md, 'E0-1'), 'CORE');
});
